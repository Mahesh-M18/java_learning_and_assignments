public class primitive_data_types {
    static void main(String[] args) {
        byte age = 20; //Small Integers
        short year = 2026; //Integers
        int salary = 50000; //Normal Integers
        long population = 14000000000L; // Large Integers
        float price = 10.5f; //Decimal numbers
        double pi = 3.14159; //More precise decimals
        char grade = 'A'; //Single character
        boolean graduated = true; //true/false

    }
}
/*
String name = "Mahesh M"
A String is not a primitive data type because it is a complex,
resizable structure made up of a collection of characters, rather than a single,
fixed-size unit of data. In languages like Java and C#, a String is a
reference data type implemented as a predefined class.
 */